    function getNestedValue(obj, key) {
        return key.split('.').reduce((cur, part) => (cur && Object.prototype.hasOwnProperty.call(cur, part)) ? cur[part] : undefined, obj);
    }

    function interpolate(str, params) {
        if (typeof str !== 'string') return str;
        return str.replace(/\{\{\s*([^}]+)\s*\}\}/g, (_, name) => {
            const key = name.trim();
            return params && Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : '';
        });
    }

    function normalizeLanguage(lang) {
        return lang === 'en' ? 'en' : 'ja';
    }

    function getLanguage() {
        try {
            return normalizeLanguage(localStorage.getItem(STORAGE_KEY) || DEFAULT_LANGUAGE);
        } catch (e) {
            return DEFAULT_LANGUAGE;
        }
    }

    function setLanguage(lang) {
        const normalized = normalizeLanguage(lang);
        try { localStorage.setItem(STORAGE_KEY, normalized); } catch (e) { /* ignore */ }
        document.documentElement.lang = normalized;
        document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { language: normalized } }));
        return normalized;
    }

    function translate(key, params, fallback, languageOverride) {
        const lang = normalizeLanguage(languageOverride || getLanguage());
        const value = getNestedValue(window.i18n[lang], key);
        const fallbackValue = getNestedValue(window.i18n[FALLBACK_LANGUAGE], key);
        const resolved = value !== undefined ? value : (fallbackValue !== undefined ? fallbackValue : (fallback !== undefined ? fallback : key));
        return interpolate(resolved, params || {});
    }

    function translateDocument(root) {
        const scope = root || document;
        if (!scope.querySelectorAll) return;
        scope.querySelectorAll('[data-i18n]').forEach((el) => {
            el.textContent = translate(el.getAttribute('data-i18n'));
        });
        scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
            el.innerHTML = translate(el.getAttribute('data-i18n-html'));
        });
        ['title', 'placeholder', 'aria-label', 'alt'].forEach((attr) => {
            scope.querySelectorAll(`[data-i18n-${attr}]`).forEach((el) => {
                el.setAttribute(attr, translate(el.getAttribute(`data-i18n-${attr}`)));
            });
        });
    }

    window.t = translate;
    window.setLanguage = setLanguage;
    window.getLanguage = getLanguage;
    window.I18n = {
        getLanguage,
        setLanguage,
        t: translate,
        translateDocument,
        locale() {
            return getLanguage() === 'ja' ? 'ja-JP' : 'en-US';
        }
    };

    document.documentElement.lang = getLanguage();
    document.addEventListener('DOMContentLoaded', () => {
        translateDocument(document);
        const observer = new MutationObserver((mutations) => {
            for (const mutation of mutations) {
                mutation.addedNodes.forEach((node) => {
                    if (node.nodeType === 1) translateDocument(node);
                });
            }
        });
        observer.observe(document.body, { childList: true, subtree: true });
    });
    document.addEventListener('i18n:changed', () => translateDocument(document));
